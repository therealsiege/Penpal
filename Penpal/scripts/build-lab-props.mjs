#!/usr/bin/env node
/**
 * Pack lab prop art from Phaser.Resources/lab into lab-props.png + frame registry.
 *
 * Source: Phaser.Resources/lab/props/SVGS (recursive .svg files, rasterized at build time)
 * Output: public/sprites/lab-props.png (64x64 cells, 12 columns)
 * Generates: src/renderer/src/game/lab-prop-frames.generated.ts
 *
 * Duplicate basenames (e.g. console/stop_button.svg vs stop_button.svg) become stem / stem_02,
 * then ordered the same way as a flat PNG export: sorted by virtual filename (localeCompare).
 *
 * @see GitHub #96 — Lab Asset Pipeline (wave-1)
 */

import sharp from 'sharp'
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'fs'
import { dirname, join, relative, resolve, sep } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const PENNY_ROOT = resolve(__dirname, '..')
const REPO_ROOT = resolve(PENNY_ROOT, '..')
const SOURCE_SVGS = resolve(REPO_ROOT, 'Phaser.Resources/lab/props/SVGS')
const OUT_DIR = resolve(PENNY_ROOT, 'public/sprites')
const GEN_TS = resolve(PENNY_ROOT, 'src/renderer/src/game/lab-prop-frames.generated.ts')

const CELL = 64
const COLS = 12

function stemToKey(stem) {
  return stem
    .replace(/-/g, '_')
    .replace(/\s+/g, '_')
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '')
    .toUpperCase()
}

/**
 * @param {string} absDir
 * @param {string[]} out
 */
function walkSvg(absDir, out) {
  for (const name of readdirSync(absDir)) {
    if (name.startsWith('.')) continue
    const p = join(absDir, name)
    const st = statSync(p)
    if (st.isDirectory()) walkSvg(p, out)
    else if (name.toLowerCase().endsWith('.svg')) out.push(p)
  }
  return out
}

/**
 * @param {Record<string, number>} frameMap
 */
function applyLegacyAliases(frameMap) {
  const copy = (alias, source) => {
    if (frameMap[source] !== undefined && frameMap[alias] === undefined) {
      frameMap[alias] = frameMap[source]
    }
  }
  copy('GAS_VALVE_OFF', 'GAS_VALVE')
  copy('GAS_VALVE_ON', 'GAS_VALVE')
  copy('CLIPBOARD_02', 'CLIPBOARD')
  copy('CUP_02', 'CUP')
  copy('PAPER_SHEET_02', 'PAPER_SHEET')
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true })

  const allAbs = walkSvg(SOURCE_SVGS, [])
  allAbs.sort((a, b) => a.localeCompare(b))

  /** @type {Map<string, number>} */
  const seenBase = new Map()
  /** @type {{ abs: string, stem: string, sortKey: string }[]} */
  const items = []

  for (const abs of allAbs) {
    const rel = relative(SOURCE_SVGS, abs).split(sep).join('/')
    const base = rel.replace(/^.*\//, '').replace(/\.svg$/i, '')
    const n = (seenBase.get(base) ?? 0) + 1
    seenBase.set(base, n)
    const stem = n === 1 ? base : `${base}_${String(n).padStart(2, '0')}`
    items.push({ abs, stem, sortKey: `${stem}.png` })
  }

  items.sort((a, b) => a.sortKey.localeCompare(b.sortKey))

  const tileCount = items.length
  const rows = Math.ceil(tileCount / COLS)
  const canvasW = COLS * CELL
  const canvasH = rows * CELL

  console.log(`Building lab-props.png...`)
  console.log(`  Source: ${SOURCE_SVGS} (SVG)`)
  console.log(`  Tiles:  ${tileCount}`)
  console.log(`  Grid:   ${COLS} cols x ${rows} rows`)
  console.log(`  Canvas: ${canvasW}x${canvasH} px`)

  const composites = []
  /** @type {Record<string, number>} */
  const frameMap = {}

  for (let i = 0; i < tileCount; i++) {
    const { abs, stem } = items[i]
    const key = stemToKey(stem)
    if (frameMap[key] !== undefined) {
      console.warn(`  WARN duplicate key ${key} from ${stem} — last frame wins`)
    }
    frameMap[key] = i

    const buf = await sharp(abs, { density: 144 })
      .resize(CELL, CELL, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .png()
      .toBuffer()

    const col = i % COLS
    const row = Math.floor(i / COLS)
    composites.push({ input: buf, left: col * CELL, top: row * CELL })
  }

  applyLegacyAliases(frameMap)

  const outPath = resolve(OUT_DIR, 'lab-props.png')
  await sharp({
    create: {
      width: canvasW,
      height: canvasH,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite(composites)
    .png()
    .toFile(outPath)

  console.log(`  Wrote ${outPath}`)

  const sortedKeys = Object.keys(frameMap).sort((a, b) => frameMap[a] - frameMap[b])
  const entries = sortedKeys.map((k) => `  ${k}: ${frameMap[k]},`).join('\n')

  const ts = `/**
 * AUTO-GENERATED by scripts/build-lab-props.mjs — do not edit by hand.
 * Frame order: virtual PNG names from Phaser.Resources/lab/props/SVGS (see build script).
 */
export const LAB_PROP_FRAMES = Object.freeze({
${entries}
} as const)

export type LabPropFrameKey = keyof typeof LAB_PROP_FRAMES
`

  writeFileSync(GEN_TS, ts, 'utf8')
  console.log(`  Wrote ${GEN_TS}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
